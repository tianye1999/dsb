import fs from 'node:fs';

const check = process.argv.includes('--check');
const output = (name, data) => {
  const url = new URL(name, import.meta.url);
  if (check) {
    if (!fs.readFileSync(url).equals(Buffer.from(data))) throw new Error(`Stale package asset: ${name}`);
  } else {
    fs.mkdirSync(new URL('.', url), {recursive: true});
    fs.writeFileSync(url, data);
  }
};
for (const name of ['bridge/task-report-store.mjs', 'bridge/active-task.mjs',
  'agent/task_report.py', 'agent/task_status.py', 'agent/feedback_export.py', 'agent/report_vocabulary.json']) {
  output('runtime/' + name, fs.readFileSync(new URL('../' + name, import.meta.url)));
}
output('LICENSE', fs.readFileSync(new URL('../LICENSE', import.meta.url)));
output('runtime/pristine-0.2.1-rc.2.html', fs.readFileSync(new URL('./tests/fixtures/pristine-0.2.1-rc.2.html', import.meta.url)));
output('runtime/restore-index.py', fs.readFileSync(new URL('../dsh-web-tweaks/restore-index.py', import.meta.url)));
const icon = fs.readFileSync(new URL('../app/res/mipmap-xxxhdpi/ic_launcher_foreground.png', import.meta.url));
if (icon.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error('Brand illustration must be PNG');
output('runtime/icon.json', JSON.stringify('data:image/png;base64,' + icon.toString('base64')));

// One owning package and one lazy factory; both original slot plugins keep their lifecycle.
const factories = ['dsb-brand', 'dsb-report'].map(name => {
  const source = fs.readFileSync(new URL(`./${name}/client.js`, import.meta.url), 'utf8');
  const prefix = `window.__ModuleLoader__.load({\n  id: '${name}',\n  factory: `;
  if (!source.startsWith(prefix) || !source.trimEnd().endsWith('\n});')) throw new Error('Unexpected client wrapper');
  return '(' + source.slice(prefix.length).trimEnd().slice(0, -4).trimEnd() + ')(require)';
});
output('client.js', `// Generated by build.mjs; edit the two source clients instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-dsb',\n  factory: require => {\n    const plugins = [${factories.join(',\n')}];\n    return {inject: [...new Set(plugins.flatMap(plugin => plugin.inject))],\n      apply(ctx) { for (const plugin of plugins) ctx.plugin(plugin); }};\n  }\n});\n`);
